			Name = "BarrierBase_" .. index,
			Shape = Enum.PartType.Cylinder,
			Size = Vector3.new(0.4, 2.4, 2.4),
			-- Flat on the floor: 0.4 thick, so its centre is at 0.2 and none of it is under the tiles.
