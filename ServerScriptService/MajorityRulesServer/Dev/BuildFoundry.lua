--[[
	BuildFoundry — the reference arena: The Foundry, a bureaucratic cathedral.

	This is the arena the game ships with until a hand-authored one exists, and it is the worked
	example every map contributor copies. Contract: docs/01-ARENA-CONTRACT.md. Design rationale,
	the fiction, the palette and the measurements behind every number: docs/13-ARENA-DESIGN.md.

	---------------------------------------------------------------------------- the fiction
	The brand is "bureaucracy gone feral" (docs/05-BRAND.md), so the arena is an institution that
	lost its mind: a hall built out of forms. Stacked paper courses over concrete, ribbed and
	buttressed, with colour-coded windows. Inside: a twelve-column colonnade on plinths stamped in
	the game's category colours, a records counter under a wall of pigeonholes, rows of desks with
	typewriters, a giant stamp press, notice boards, planters, queue barriers, turnstiles, filing
	banks, pipework, banners, a gallery level and four corner balconies. The walls that *move* are
	not the building — they are office partitions, which is why it reads as intentional when
	Small Map and Shrinking Arena slide them inward.

	Everything bright means something: lime is the vote, gold is the verdict, and the eight
	modifier categories own the eight hues used by the columns, window bays, banners and lamps.

	--------------------------------------------------------------------------- the geometry
	* 16x16 tiles of 7.5 studs with a 0.5 grout gap = 256 tiles over a 128x128 play space. The
	  grout substrate does not collide and the plinth is a *frame*, so a collapsed tile is a real
	  hole rather than a two-stud step (D-032).
	* Partitions 34 high, above LowGravity's own 22.8-stud jump apex, so gravity is not a way out.
	* Twenty cover pieces: twelve on a radius-34 colonnade and eight inner ones ringing the dais.
	* Two levels: an elevated gallery circuit along all four walls at y=8, turning the corners into
	  corner balconies, reached by stairs along the walls (8 risers of 1.0). A normal jump apex is
	  6.4 studs, so the upper level is stairs-only until someone votes LowGravity.
	* Seven crates for eight players: one on the gold dais, four in mid field, two near the walls.
	* The hall is long enough that a player who walks in a straight line for 30 seconds has crossed
	  it twice (128 studs at WalkSpeed 16 is 8 seconds), which is the point of the size: a fight
	  that starts anywhere can be reinforced or fled from instead of being decided in one burst.

	------------------------------------------------------------------------------- the rules
	* An invisible, non-colliding part is a marker and must not block a ray (`CanQuery = false`).
	  The part helper applies that automatically; six 64x64 emitter plates once ate every shot in
	  the hall and blinded every bot (D-031).
	* A low, visible prop is `Decor`: non-colliding and non-queryable, so players walk over it and
	  bullets ignore it. Anything taller than ~1.5 studs is solid.
	* Clearances (spawn to cover, crate to cover) are measured by ArenaValidator, which runs at
	  the end of the build and reports loudly. This arena's predecessor passed a validator that
	  never checked clearance and was unplayable in four spawns out of eight.
]]--

