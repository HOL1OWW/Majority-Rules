--! Runs the contract's own gate over what we just built, and says so loudly when it cannot. A
--! generator that skips its check on failure is worse than one with no check: the reference arena
--! this replaced failed the clearance rule in ten places and nothing ever looked.
function BuildFoundry.report(arena: Model)
	local tools = ServerStorage:FindFirstChild("Tools")
	local module = tools and tools:FindFirstChild("ArenaValidator")
	if not module then
		Log.warn("Foundry built UNVERIFIED: ServerStorage.Tools.ArenaValidator is missing")
		return
	end

	-- require caches per session and Rojo patches module source in place, so a cached validator can
	-- silently be an old one. Load a clone to be sure this is the real check.
	local clone = module:Clone()
	clone.Name = "ArenaValidator_buildcheck"
	clone.Parent = tools
	local ok, Validator = pcall(require, clone)
	clone:Destroy()
	if not ok then
		Log.warn("Foundry built UNVERIFIED: validator failed to load (%s)", tostring(Validator))
		return
	end

	local result = Validator.validate(arena)
	if result.ok then
		Log.info(
			"Foundry passes ArenaValidator: %d parts, %d spawns, %d loot, %d cameras, smallest loot clearance %.1f studs",
			result.info.parts,
			result.info.spawns,
			result.info.lootPoints,
			result.info.voteCameras,
			result.info.minLootClearance or -1
		)
	else
		for _, message in result.errors do
			Log.error("Foundry FAILS ArenaValidator: %s", message)
		end
	end
	for _, message in result.warnings do
		Log.warn("Foundry validator warning: %s", message)
	end
end

-- Bootstrap requires this module when no arena exists in ServerStorage.Arenas, and `require` on a
-- module that returns nothing fails with "Module code did not return exactly one value".
return BuildFoundry
