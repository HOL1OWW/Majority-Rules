			}, floor)
		end
	end

	-- ------------------------------------------------------------------ partitions
	-- These are the parts modifiers move. Authored as office slats so that when Small Map and
	-- Shrinking Arena slide them inward it reads as the institution closing in.
	local walls = folder("Walls", transforms)
	local wallSpecs = {
		{ Size = Vector3.new(HALF * 2 + WALL_THICKNESS * 2, WALL_HEIGHT, WALL_THICKNESS), Position = Vector3.new(0, 0, -HALF) },
		{ Size = Vector3.new(HALF * 2 + WALL_THICKNESS * 2, WALL_HEIGHT, WALL_THICKNESS), Position = Vector3.new(0, 0, HALF) },
		{ Size = Vector3.new(WALL_THICKNESS, WALL_HEIGHT, HALF * 2), Position = Vector3.new(-HALF, 0, 0) },
		{ Size = Vector3.new(WALL_THICKNESS, WALL_HEIGHT, HALF * 2), Position = Vector3.new(HALF, 0, 0) },
	}
	for index, spec in wallSpecs do
		local alongX = spec.Size.Z == WALL_THICKNESS
		part({
			Name = "Wall_" .. index,
			Size = Vector3.new(spec.Size.X, WALL_HEIGHT, spec.Size.Z),
			Position = spec.Position + Vector3.new(0, WALL_HEIGHT / 2, 0),
			Color = GRAPHITE,
			Material = Enum.Material.DiamondPlate,
			Attributes = {
				[Tags.Attr.TransformGroup] = "Wall",
				[Tags.Attr.CanScale] = true,
				[Tags.Attr.CanHide] = false,
				[Tags.Attr.AnchorState] = "Shown",
			},
			Tags = { Tags.Transformable },
		}, walls)

		for slat = 1, math.floor((WALL_HEIGHT - 6) / 4) do
			local y = slat * 4 - 2
			part({
				Name = "WallSlat_" .. index .. "_" .. slat,
				Size = alongX and Vector3.new(spec.Size.X - 2.4, 1.8, WALL_THICKNESS + 0.5)
					or Vector3.new(WALL_THICKNESS + 0.5, 1.8, spec.Size.Z - 2.4),
				Position = spec.Position + Vector3.new(0, y, 0),
				Color = slat % 2 == 0 and PAPER or GRAPHITE_SOFT,
				Material = Enum.Material.Metal,
				TopSurface = Enum.SurfaceType.Inlet,
				Attributes = {
					[Tags.Attr.TransformGroup] = "Wall",
					[Tags.Attr.CanScale] = true,
					[Tags.Attr.CanHide] = false,
					[Tags.Attr.AnchorState] = "Shown",
				},
				Tags = { Tags.Transformable },
			}, walls)
		end
	end

	-- ------------------------------------------------------------------ the shell
	local shell = folder("Shell", geometry)
	for _, spec in {
		{ Name = "Shell_N", Size = Vector3.new(SHELL_HALF * 2 + SHELL_THICKNESS * 2, SHELL_HEIGHT, SHELL_THICKNESS), Position = Vector3.new(0, 0, -SHELL_HALF) },
		{ Name = "Shell_S", Size = Vector3.new(SHELL_HALF * 2 + SHELL_THICKNESS * 2, SHELL_HEIGHT, SHELL_THICKNESS), Position = Vector3.new(0, 0, SHELL_HALF) },
		{ Name = "Shell_W", Size = Vector3.new(SHELL_THICKNESS, SHELL_HEIGHT, SHELL_HALF * 2), Position = Vector3.new(-SHELL_HALF, 0, 0) },
		{ Name = "Shell_E", Size = Vector3.new(SHELL_THICKNESS, SHELL_HEIGHT, SHELL_HALF * 2), Position = Vector3.new(SHELL_HALF, 0, 0) },
	} do
		shellWall(spec.Name, spec.Size, spec.Position, spec.Size.Z == SHELL_THICKNESS, shell)
	end

	-- The title, in blocky neon, on the north wall above the Clerk's box.
	local marquee = Instance.new("Model")
	marquee.Name = "Marquee"
	marquee.Parent = shell
	-- In front of the buttresses, not in the wall: the ribs project 4.5 studs further into the hall than
	-- the wall's own face, so a marquee set flush with the wall was buried inside three of them.
	--
