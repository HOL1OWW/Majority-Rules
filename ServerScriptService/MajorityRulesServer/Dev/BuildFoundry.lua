--! The elevated circuit: two long galleries along the north and south walls that join the four
--! corner balconies, so the upper level is a loop rather than four islands. Segmented deck, rails on
--! the arena side only (the wall side is the wall), and struts down to the partitions.
--! One gallery wall, built along whichever axis that wall runs on. `signX` and `signZ` say which
--! wall (`{0, 1}` = south, `{-1, 0}` = west); exactly one of them is non-zero. The run axis is X for
--! the north and south walls and Z for the east and west ones, so every part is described in local
--! terms — run length, height, depth — and mapped onto the world axis at the end. Copying the
--! construction per wall instead is how four walls drift apart from each other.
local function gallery(signX: number, signZ: number, parent: Instance)
	local alongX = signX == 0
	local sign = alongX and signZ or signX
	local label = alongX and (signZ > 0 and "S" or "N") or (signX > 0 and "E" or "W")
	local deckDepth = HALF - 0.8 - GALLERY_DEPTH / 2 -- centred so the outer edge touches the wall

	-- run = distance along the wall (always centred on 0), depth = distance out from the centre,
	-- measured towards the wall the gallery hangs on.
	local function place(run: number, y: number, depth: number): Vector3
		if alongX then
			return Vector3.new(run, y, sign * depth)
		end
		return Vector3.new(sign * depth, y, run)
	end
	local function sized(run: number, height: number, depth: number): Vector3
		if alongX then
			return Vector3.new(run, height, depth)
		end
		return Vector3.new(depth, height, run)
	end

	local segments = 6
	local span = GALLERY_HALF * 2
	local width = span / segments

	for index = 1, segments do
		local run = -GALLERY_HALF + (index - 0.5) * width
		part({
			Name = "Gallery_" .. label .. "_" .. index,
			Size = sized(width - 0.6, 1, GALLERY_DEPTH),
			Position = place(run, UPPER_Y - 0.5, deckDepth),
			Color = GRAPHITE_SOFT,
			Material = Enum.Material.DiamondPlate,
			TopSurface = Enum.SurfaceType.Studs,
			Tags = { Tags.Static },
		}, parent)

		part({
			Name = "GalleryStrut_" .. label .. "_" .. index,
			Size = Vector3.new(0.8, UPPER_Y - 1, 0.8),
			Position = place(run - width / 2 + 1, (UPPER_Y - 1) / 2, deckDepth - (GALLERY_DEPTH / 2 - 0.6)),
			Color = GRAPHITE,
			Material = Enum.Material.CorrodedMetal,
			Tags = { Tags.Static },
		}, parent)
	end

	part({
		Name = "GalleryRail_" .. label,
		Size = sized(span, 3.2, 0.7),
		Position = place(0, UPPER_Y + 1.6, deckDepth - (GALLERY_DEPTH / 2 - 0.35)),
		Color = PAPER,
		Material = Enum.Material.Metal,
		Tags = { Tags.Static },
	}, parent)

	part({
		Name = "GalleryLip_" .. label,
		Size = sized(span, 0.4, 0.7),
		Position = place(0, UPPER_Y + 0.2, deckDepth - (GALLERY_DEPTH / 2 - 0.1)),
		Color = GOLD,
		Material = Enum.Material.Neon,
		Decor = true,
		Tags = { Tags.Static },
	}, parent)

	-- Hanging signs over the gallery, one every other segment: institutional wayfinding. The colour
	-- stripe is on the arena-facing face, which is depth *minus* the offset: the old version added
	-- it, so on two of the four walls the stripe was behind the board.
	for index = 1, segments, 2 do
		local run = -GALLERY_HALF + (index - 0.5) * width
		part({
			Name = "GallerySign_" .. label .. "_" .. index,
			Size = sized(9, 2.4, 0.3),
			Position = place(run, UPPER_Y + 5, deckDepth),
			Color = PAPER,
			Material = Enum.Material.Metal,
			Tags = { Tags.Static },
		}, parent)
		part({
			Name = "GallerySignBar_" .. label .. "_" .. index,
			Size = sized(6.5, 0.7, 0.25),
			Position = place(run, UPPER_Y + 5, deckDepth - 0.25),
			Color = CATEGORY[(index + (sign > 0 and 3 or 0)) % #CATEGORY + 1],
			Material = Enum.Material.Neon,
			Decor = true,
			Tags = { Tags.Static },
		}, parent)
	end
end

