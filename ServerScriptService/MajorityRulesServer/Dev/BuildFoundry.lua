-- --------------------------------------------------------------------------- placement guard
--! World-space bounds of every visible part placed so far.
--!
--! The clutter in this hall used to be positioned by hand from a screenshot, and the placement probe
--! found what that produces: four desks inside a colonnade column, four ballot stacks under cover
--! pieces, two mail carts inside filing banks, a stamp press inside a column. Those were not
--! composition errors, they were *arithmetic* errors — a stud count that stopped matching the
--! geometry the moment the hall was resized. This table and `settle` turn each of them into a rule:
--! a prop goes at the first point along its own lane where its footprint clears everything already
--! built. Rotated parts register their axis-aligned box, which is conservative, and conservative is
--! the right direction for a guard.
local occupied: { { min: Vector3, max: Vector3, name: string } } = {}

local GUARD_MARGIN = 0.4 -- studs of air a prop must leave around its footprint
local GUARD_FLOOR = 0.6 -- bounds entirely below this are floor decor; a prop may stand on them

--! Names of the building itself. A prop is *meant* to abut these — a filing bank's back sits 0.25
--! studs off the wall slats, a notice board 0.05 — so the guard must not demand clearance from them,
--! or every wall-mounted prop fails its search and stays where it was. The first version did exactly
--! that: all fourteen banks, all three notice boards and one barrier reported "found no clear ground"
--! and nothing moved. Cover is deliberately *not* in this list: props must avoid cover.
--! Only the surfaces a prop is mounted *on*: the partitions and their slats, the building's own
--! shell, the plinth, the floor. Deliberately not the upper level, the stairs or the dais — those are
--! things props must still avoid, and a bank that slid along its wall into a balcony leg is one of the
--! collisions this guard exists to prevent.
local STRUCTURE = { "^Wall", "^Shell", "^Base_", "^Tile", "^Lava" }

local function isStructure(name: string): boolean
	for _, pattern in STRUCTURE do
		if string.match(name, pattern) then
			return true
		end
	end
	return false
end

local function registerBounds(instance: BasePart)
	if instance.Transparency >= 0.9 then
		return -- invisible: a marker, and nothing collides with what cannot be seen
	end
	local cf, size = instance.CFrame, instance.Size
	local half = size * 0.5
	local extents = Vector3.new(
		math.abs(cf.RightVector.X) * half.X + math.abs(cf.UpVector.X) * half.Y + math.abs(cf.LookVector.X) * half.Z,
		math.abs(cf.RightVector.Y) * half.X + math.abs(cf.UpVector.Y) * half.Y + math.abs(cf.LookVector.Y) * half.Z,
		math.abs(cf.RightVector.Z) * half.X + math.abs(cf.UpVector.Z) * half.Y + math.abs(cf.LookVector.Z) * half.Z
	)
	local box = {
		min = cf.Position - extents,
		max = cf.Position + extents,
		name = instance.Name,
		structure = isStructure(instance.Name),
	}
	if box.max.Y >= GUARD_FLOOR then
		table.insert(occupied, box)
	end
end

--! Register a box that props must step around but which is not built yet: the crate pads and the
--! spawn volumes are placed at the end of `build`, and their positions come from the ring constants,
--! so they can be reserved here. A crate that spawns inside a prop is worse than a prop that moved.
local function keepOut(position: Vector3, size: Vector3, name: string)
	table.insert(occupied, {
		min = Vector3.new(position.X - size.X / 2, position.Y, position.Z - size.Z / 2),
		max = Vector3.new(position.X + size.X / 2, position.Y + size.Y, position.Z + size.Z / 2),
		name = name,
	})
end

local function clearAt(position: Vector3, size: Vector3): boolean
	if math.abs(position.X) + size.X / 2 > HALF - 0.5 or math.abs(position.Z) + size.Z / 2 > HALF - 0.5 then
		return false -- outside the partitions
	end
	local minX, maxX = position.X - size.X / 2 - GUARD_MARGIN, position.X + size.X / 2 + GUARD_MARGIN
	local minZ, maxZ = position.Z - size.Z / 2 - GUARD_MARGIN, position.Z + size.Z / 2 + GUARD_MARGIN
	for _, box in occupied do
		if not box.structure and box.max.Y > 0.05 and box.min.Y < size.Y then
			if maxX > box.min.X and minX < box.max.X and maxZ > box.min.Z and minZ < box.max.Z then
				return false
			end
		end
	end
	return true
end

--! One part, with the arena's two standing rules applied. `Decor = true` marks a low visible prop:
--! it must not be walked into (CanCollide) or shot (CanQuery). Invisible non-colliding parts get
--! both flags too — they are markers, and a marker that blocks a ray is a wall you cannot see.
local function part(props: { [string]: any }, parent: Instance): BasePart
	local className = props.ClassName or "Part"
	props.ClassName = nil
	local instance = Instance.new(className)
	instance.Anchored = true
	instance.CanCollide = true
	instance.TopSurface = Enum.SurfaceType.Smooth
	instance.BottomSurface = Enum.SurfaceType.Smooth
	instance.Material = Enum.Material.SmoothPlastic
	for key, value in props do
		if key == "Attributes" then
			for attributeName, attributeValue in value do
				instance:SetAttribute(attributeName, attributeValue)
			end
		elseif key == "Tags" then
			for _, tag in value do
				CollectionService:AddTag(instance, tag)
			end
		elseif key == "Decor" then
			instance.CanCollide = false
		else
			(instance :: any)[key] = value
		end
	end
	if props.Decor or (instance.Transparency >= 1 and not instance.CanCollide) then
		instance.CanQuery = false
		instance.CanTouch = false
	end
	if props.Decor then
		instance.CanCollide = false
	end
	instance.Parent = parent
	registerBounds(instance)
	return instance
end

--! Slide a prop along its own lane until its footprint is clear, leaving the other coordinate exactly
--! where the author put it — which is what keeps wall furniture against the wall instead of drifting
--! into the room. `size` is the footprint plus height the prop occupies. The authored position is
--! always candidate zero, so a prop only moves when it has to.
local function settle(preferred: Vector3, size: Vector3, label: string, alongX: boolean, step: number, tries: number): Vector3
	-- Two passes: along the prop's own lane first, so wall furniture stays against its wall, and then
	-- across it. The second pass exists because a 21-stud queue barrier set across a ring of crate pads
	-- cannot clear them by sliding *along* itself — the pads are off to the side of the line, and one of
	-- the four barriers reported "no clear ground" for exactly that reason.
	for pass = 1, 2 do
		local lane = (pass == 1) == alongX
		for attempt = 0, tries do
			for _, sign in { 1, -1 } do
				if pass == 1 or attempt > 0 then
					local distance = attempt == 0 and 0 or attempt * step * sign
					local candidate = lane and preferred + Vector3.new(distance, 0, 0) or preferred + Vector3.new(0, 0, distance)
					if clearAt(candidate, size) then
						if attempt > 0 then
							Log.info(
								"BuildFoundry: %s slid %.1f studs %s to clear the geometry",
								label,
								math.abs(distance),
								lane and "along its lane" or "across its lane"
							)
						end
						return candidate
					end
				end
			end
		end
	end
	Log.warn("BuildFoundry: %s found no clear ground within %.0f studs; left where the author put it", label, tries * step)
	return preferred
end

local function colourOf(value): Color3
	if type(value) == "string" then
		return NAMED[value] or GRAPHITE
	end
	return value
end

--! A rectangular frame of boxes: used for the plinth courses, and for anything that has to be a ring
--! rather than a slab. A slab under the floor would seal the arena's underside.
local function frame(name: string, inner: number, outer: number, height: number, y: number, colour, material, parent: Instance)
	local band = outer - inner
	local offset = inner + band / 2
	for _, side in { { 0, -1 }, { 0, 1 }, { -1, 0 }, { 1, 0 } } do
		local alongX = side[2] ~= 0
		part({
			Name = name .. (alongX and (side[2] > 0 and "_S" or "_N") or (side[1] > 0 and "_E" or "_W")),
			Size = alongX and Vector3.new(outer * 2, height, band) or Vector3.new(band, height, inner * 2),
			Position = alongX and Vector3.new(0, y, side[2] * offset) or Vector3.new(side[1] * offset, y, 0),
			Color = colourOf(colour),
			Material = material,
			TopSurface = Enum.SurfaceType.Studs,
			Tags = { Tags.Static },
		}, parent)
	end
end

--! A line of blocky letters, built from plates. Used for the VOTE marquee; the only "text" in the
--! arena that is not a texture. Letters are deliberately crude — this is signage, not typography.
local LETTERS = {
	V = { { 0, -1.1, 1, 0.35, 1.5, -0.5 }, { 0, -1.1, 1, 0.35, 1.5, 0.5 }, { 0, 0.6, 1.6, 0.3, 1.5, 0 } },
	O = { { 0, 0, 1.6, 0.35, 3, -1.1 }, { 0, 0, 1.6, 0.35, 3, 1.1 }, { -0.6, 0, 0.35, 3, 0.4, 0 }, { 0.6, 0, 0.35, 3, 0.4, 0 } },
	T = { { 0, 1.4, 1.8, 0.35, 0.4, 0 }, { 0, 0, 0.35, 3, 0.3, 0 } },
	E = { { 0, 0, 0.35, 3, 1.4, -1.1 }, { 0, 1.3, 1.2, 0.35, 0.5, 0 }, { 0, 0, 1.2, 0.35, 0.5, 0 }, { 0, -1.3, 1.2, 0.35, 0.5, 0 } },
}

local function sign(text: string, cframe: CFrame, scale: number, glow: Color3, parent: Instance)
	local cursor = 0
	for index = 1, #text do
		local glyph = LETTERS[string.sub(text, index, index)]
		if glyph then
			for _, cell in glyph do
				part({
					Name = "Sign_" .. text .. "_" .. index,
					Size = Vector3.new(cell[3] * scale, cell[4] * scale, cell[5] * scale),
					CFrame = cframe * CFrame.new((cursor + cell[1] * scale), cell[2] * scale, 0),
					Color = glow,
					Material = Enum.Material.Neon,
					Transparency = 0.05,
					CanCollide = false,
					Tags = { Tags.Static },
				}, parent)
			end
			cursor += 2.2 * scale
		end
	end
	return cursor
end

--! One cover piece, dressed as a column. The 7x6x7 box is the contract's cover volume and the thing
--! ArenaValidator measures; the plinth, band and capital exist to make the ring read as architecture
--! and to carry the category colour of that column. Every part of the dressing is inside the box or
--! thin, so the clearance measurement stays honest.
local function coverColumn(index: number, radius: number, angle: number, parent: Instance)
	local hue = CATEGORY[((index - 1) % #CATEGORY) + 1]
	local position = Vector3.new(math.cos(angle) * radius, 0, math.sin(angle) * radius)
	local facing = CFrame.new(position) * CFrame.Angles(0, -angle, 0)
	local tag = string.format("%02d", index)

	local attributes = {
		[Tags.Attr.TransformGroup] = "Cover",
		[Tags.Attr.CanHide] = true,
		[Tags.Attr.AnchorState] = "Hidden",
	}

	part({
		Name = "Cover_Base_" .. tag,
		Size = COVER_BASE_SIZE,
		CFrame = facing * CFrame.new(0, COVER_BASE_SIZE.Y / 2, 0),
		Color = hue,
		Material = Enum.Material.Marble,
		Attributes = attributes,
		Tags = { Tags.Transformable },
	}, parent)

	local shaft = part({
		Name = "Cover_" .. tag,
		Size = COVER_SIZE,
		CFrame = facing * CFrame.new(0, COVER_BASE_SIZE.Y + COVER_SIZE.Y / 2, 0),
		Color = GRAPHITE_SOFT,
		Material = Enum.Material.Concrete,
		TopSurface = Enum.SurfaceType.Inlet,
		Attributes = attributes,
		Tags = { Tags.Transformable },
	}, parent)

	part({
		Name = "Cover_Band_" .. tag,
		Size = Vector3.new(COVER_SIZE.X + 0.08, 0.5, COVER_SIZE.Z + 0.08),
		CFrame = facing * CFrame.new(0, COVER_BASE_SIZE.Y + COVER_SIZE.Y * 0.55, 0),
		Color = hue,
		Material = Enum.Material.Neon,
		Transparency = 0.15,
		Attributes = attributes,
		Tags = { Tags.Transformable },
	}, parent)

	part({
		Name = "Cover_Capital_" .. tag,
		Size = COVER_CAPITAL_SIZE,
		CFrame = facing * CFrame.new(0, COVER_BASE_SIZE.Y + COVER_SIZE.Y + COVER_CAPITAL_SIZE.Y / 2, 0),
		Color = hue,
		Material = Enum.Material.Marble,
		Attributes = attributes,
		Tags = { Tags.Transformable },
	}, parent)

	return shaft
end

--! A flight of steps from the floor up to a balcony, run along the wall its corner belongs to.
--! (A flight aimed diagonally in from the corner runs straight through the colonnade — the columns
--! sit at exactly the diagonal angles — which shipped once and was found by probe, not by reading.)
local function staircase(signX: number, signZ: number, parent: Instance)
	local innerEdge = BALCONY_CENTER - BALCONY_SIZE / 2 -- the balcony's inner edge
	-- The flight runs in the inboard half of the balcony's width, not its centre: the gallery deck of
	-- the wall it lands beside is 7 deep, so a centred flight would pass through it on the way up.
	local width = BALCONY_SIZE - GALLERY_DEPTH - 0.8
	local lane = BALCONY_CENTER - GALLERY_DEPTH / 2 - 0.4

	for step = 1, STAIR_STEPS do
		local height = STAIR_RISE * step
		local along = innerEdge - (STAIR_STEPS - step + 0.5) * STAIR_RUN
		part({
			Name = "Stair_" .. step .. "_" .. (signX > 0 and "E" or "W") .. (signZ > 0 and "S" or "N"),
			Size = Vector3.new(STAIR_RUN + 0.2, height, width),
			Position = Vector3.new(signX * along, height / 2, signZ * lane),
			Color = GRAPHITE,
			Material = Enum.Material.Concrete,
			TopSurface = Enum.SurfaceType.Studs,
			Tags = { Tags.Static },
		}, parent)

		part({
			Name = "StairNosing",
			Size = Vector3.new(0.5, 0.3, width),
			Position = Vector3.new(signX * (along + (STAIR_RUN + 0.2) / 2 - 0.25), height + 0.15, signZ * lane),
			Color = PAPER,
			Material = Enum.Material.Metal,
			Decor = true,
			Tags = { Tags.Static },
		}, parent)
	end
end

--! A balcony: deck, rail on the two outward edges, legs, and a gold lip on the inner faces. High
--! ground that is reachable on foot and drop-off only.
local function balcony(signX: number, signZ: number, parent: Instance)
	local centre = Vector3.new(signX * BALCONY_CENTER, 0, signZ * BALCONY_CENTER)
	local label = (signX > 0 and "E" or "W") .. (signZ > 0 and "S" or "N")

	part({
		Name = "Balcony_" .. label,
		Size = Vector3.new(BALCONY_SIZE, 1, BALCONY_SIZE),
		Position = Vector3.new(centre.X, UPPER_Y - 0.5, centre.Z),
		Color = GRAPHITE_SOFT,
		Material = Enum.Material.DiamondPlate,
		TopSurface = Enum.SurfaceType.Studs,
		Tags = { Tags.Static },
	}, parent)

	for _, edge in { { signX, 0 }, { 0, signZ } } do
		local alongX = edge[1] ~= 0
		part({
			Name = "BalconyRail_" .. label,
			Size = alongX and Vector3.new(0.7, 3.2, BALCONY_SIZE) or Vector3.new(BALCONY_SIZE, 3.2, 0.7),
			Position = Vector3.new(
				centre.X + edge[1] * (BALCONY_SIZE / 2 - 0.35),
				UPPER_Y + 1.6,
				centre.Z + edge[2] * (BALCONY_SIZE / 2 - 0.35)
			),
			Color = PAPER,
			Material = Enum.Material.Metal,
			Tags = { Tags.Static },
		}, parent)
	end

	part({
		Name = "BalconyLip_" .. label,
		Size = Vector3.new(BALCONY_SIZE, 0.4, 0.7),
		Position = Vector3.new(centre.X - signX * (BALCONY_SIZE / 2 - 0.1), UPPER_Y + 0.2, centre.Z),
		Color = GOLD,
