--! Lighting is part of the design, not a default: dusk, haze, bloom, and warm lamps. The Fog,
--! Blackout and LowGravity modifiers all write to Lighting too, and GameplayService captures its
--! baseline at round start, so this is the look every modifier departs from and returns to.
local function applyLighting()
	Lighting.ClockTime = 18.1
	Lighting.Brightness = 2.2
	Lighting.Ambient = Color3.fromRGB(52, 52, 62)
	Lighting.OutdoorAmbient = Color3.fromRGB(40, 42, 54)
	Lighting.GlobalShadows = true
	Lighting.FogEnd = 2600
	Lighting.FogStart = 800

	local function ensure(className: string): Instance
		local existing = Lighting:FindFirstChildOfClass(className)
		if existing then
			return existing
		end
		local instance = Instance.new(className)
		instance.Parent = Lighting
		return instance
	end

	local atmosphere = ensure("Atmosphere") :: Atmosphere
	atmosphere.Density = 0.34
	atmosphere.Offset = 0.2
	atmosphere.Color = Color3.fromRGB(228, 224, 214)
	atmosphere.Decay = Color3.fromRGB(70, 72, 84)
	atmosphere.Glare = 0.16
	atmosphere.Haze = 1.6

	local bloom = ensure("BloomEffect") :: BloomEffect
	bloom.Intensity = 1.1
	bloom.Size = 28
	bloom.Threshold = 0.92

	local colour = ensure("ColorCorrectionEffect") :: ColorCorrectionEffect
	colour.Saturation = 0.17
	colour.Contrast = 0.11
	colour.TintColor = Color3.fromRGB(255, 246, 232)
	colour.Brightness = 0

	local rays = ensure("SunRaysEffect") :: SunRaysEffect
	rays.Intensity = 0.12
	rays.Spread = 0.9
end

-- ------------------------------------------------------------------------------------ build
function BuildFoundry.build(): Model
	local container = ServerStorage:FindFirstChild("Arenas")
	if not container or not container:IsA("Folder") then
		container = Instance.new("Folder")
		container.Name = "Arenas"
		container.Parent = ServerStorage
	end

	local existing = container:FindFirstChild("Foundry")
	if existing then
		existing:Destroy()
	end

	local arena = Instance.new("Model")
	arena.Name = "Foundry"

	-- ------------------------------------------------------------------ root attributes
	arena:SetAttribute(Tags.Attr.ArenaId, "Foundry")
	arena:SetAttribute(Tags.Attr.DisplayName, "THE FOUNDRY")
	arena:SetAttribute(Tags.Attr.MinPlayers, 1)
	arena:SetAttribute(Tags.Attr.MaxPlayers, 8)
	arena:SetAttribute(Tags.Attr.SizeClass, "Large")
	-- Vertical is honest: a gallery circuit at 7 studs joining four corner balconies, stairs-only
	-- under normal gravity and jump-reachable under Low Gravity.
	arena:SetAttribute(Tags.Attr.FeatureTags, "Cover,FlatFloor,Tiles,Hazard,Lava,Vertical")
	arena:SetAttribute(Tags.Attr.FloorY, 0)
	arena:SetAttribute(Tags.Attr.Weight, 10)
	-- Read by Bootstrap: a stale arena is rebuilt before the first round rather than played.
	arena:SetAttribute("GeneratorRevision", BuildFoundry.Revision)

	local geometry = folder("Geometry", arena)
	local transforms = folder("Transforms", arena)

	-- ------------------------------------------------------------------ stepped frame plinth
	-- A frame, not a slab. A solid plinth under the floor would put concrete two studs below the
	-- tiles, so a collapsed tile would be a step down instead of a hole, and Collapsing Floor would
	-- be pure decoration. The interior stays open all the way to the lava.
	for index, course in BASE_COURSES do
		frame(
			"Base_" .. index,
			HALF - 1,
			course[1],
			course[2] * 2,
			-TILE_THICKNESS - course[2],
			course[3],
			index == #BASE_COURSES and Enum.Material.Slate or Enum.Material.Granite,
			geometry
		)
	end

	-- The arena pivot sits on the floor's centre axis and nothing else does, because the plinth is a
	-- frame. ArenaService.Center() reads this, and every group scale is about it.
	local pivot = part({
		Name = "ArenaPivot",
		Size = Vector3.new(1, 1, 1),
		Position = Vector3.zero,
		Transparency = 1,
		CanCollide = false,
		Tags = { Tags.Static },
	}, geometry)

	local floor = folder("Floor", transforms)

	part({
		Name = "FloorSubstrate",
		Size = Vector3.new(GRID * (TILE + TILE_GAP) + 1, 1, GRID * (TILE + TILE_GAP) + 1),
		Position = Vector3.new(0, -TILE_THICKNESS - 0.5, 0),
		Color = INK,
		Material = Enum.Material.Slate,
		CanCollide = false,
		Tags = { Tags.Static },
	}, geometry)

	local pitch = TILE + TILE_GAP
	local tileIndex = 0
	for row = 0, GRID - 1 do
		for column = 0, GRID - 1 do
			tileIndex += 1
			local x = (column - (GRID - 1) / 2) * pitch
			local z = (row - (GRID - 1) / 2) * pitch
			-- Checkerboard, so which tile has gone is legible from the far side of the hall, with a
			-- lime seal tile every fourth row and column: the institution's own pattern.
			local light = (row + column) % 2 == 0
			local seal = row % 4 == 0 and column % 4 == 0
			part({
				Name = "Tile_" .. tileIndex,
				Size = Vector3.new(TILE, TILE_THICKNESS, TILE),
				Position = Vector3.new(x, -TILE_THICKNESS / 2, z),
				Color = seal and ACCENT or (light and GRAPHITE_SOFT or GRAPHITE),
				Material = light and Enum.Material.CeramicTiles or Enum.Material.Pavement,
				Attributes = {
					[Tags.Attr.TransformGroup] = "Floor,Tile_" .. tileIndex,
					[Tags.Attr.CanScale] = true,
					[Tags.Attr.CanHide] = true,
					[Tags.Attr.CanMorph] = true,
					[Tags.Attr.AnchorState] = "Shown",
