	-- were 3.4-stud bars lying horizontally at chest height, the bases were 2.4-stud discs standing
	-- on their rims with a stud of themselves under the floor, and the "ropes" were 1.2 studs long,
	-- leaving 5.8 studs of nothing between posts. `upright` turns the first two into a post and a
	-- footplate; the rope needs no rotation when the queue runs along X and a quarter turn when it
	-- runs along Z.
