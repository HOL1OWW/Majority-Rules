		local along = alongX and Vector3.new(offset, 0, 0) or Vector3.new(0, 0, offset)
		local hue = CATEGORY[((index - 1) % #CATEGORY) + 1]
		local bay = span / WINDOW_BAYS - 7
		part({
			Name = name .. "_Window",
